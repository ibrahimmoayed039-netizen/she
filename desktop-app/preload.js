const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (s) => ipcRenderer.invoke('settings:set', s),
  pickKey: () => ipcRenderer.invoke('key:pick'),
  connect: () => ipcRenderer.invoke('connect'),
  testOllama: () => ipcRenderer.invoke('ollama:test'),
  analyze: (id) => ipcRenderer.invoke('analyze', id),
  pickImage: () => ipcRenderer.invoke('image:pick'),
  addComplaint: (d) => ipcRenderer.invoke('complaint:add', d),
  setPriority: (id, p) => ipcRenderer.invoke('priority:set', id, p),
  createDeptStaff: (p) => ipcRenderer.invoke('staff:createDept', p),
  onDeptCrews: (cb) => ipcRenderer.on('deptCrews', (_, d) => cb(d)),
  editCrews: (dept, add, remove) => ipcRenderer.invoke('crews:edit', dept, add, remove),
  setStaffName: (id, name) => ipcRenderer.invoke('staff:setName', id, name),
  setStaffPassword: (id, pw) => ipcRenderer.invoke('staff:setPassword', id, pw),
  setStaffDisabled: (id, f) => ipcRenderer.invoke('staff:setDisabled', id, f),
  deleteStaff: (id) => ipcRenderer.invoke('staff:delete', id),
  createCrew: (p) => ipcRenderer.invoke('crew:create', p),
  materialsReady: (id) => ipcRenderer.invoke('materials:ready', id),
  materialsStatus: (id, status, note) => ipcRenderer.invoke('materials:status', id, status, note),
  reviewApprove: (id) => ipcRenderer.invoke('review:approve', id),
  reviewReturn: (id, note) => ipcRenderer.invoke('review:return', id, note),
  getLog: (id) => ipcRenderer.invoke('log:get', id),
  openMap: (lat, lng) => ipcRenderer.invoke('map:open', lat, lng),
  onStaff: (cb) => ipcRenderer.on('staff', (_, d) => cb(d)),
  onComplaints: (cb) => ipcRenderer.on('complaints', (_, d) => cb(d)),
  onLog: (cb) => ipcRenderer.on('log', (_, m) => cb(m)),
});
